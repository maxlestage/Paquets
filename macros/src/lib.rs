//! Attribute macros of [Paquets](https://docs.rs/paquets).
//!
//! This crate is an implementation detail: depend on `paquets`, which re-exports
//! [`macro@model`] and [`macro@data`] in its prelude.

use std::collections::HashSet;

use proc_macro::TokenStream;
use proc_macro2::TokenStream as TokenStream2;
use quote::quote;
use syn::parse::Parser as _;
use syn::punctuated::Punctuated;
use syn::{Attribute, Fields, ItemStruct, LitStr, Path, Token, Type, parse_macro_input};

/// Turns a struct into a database table that also travels as JSON.
///
/// ```ignore
/// use paquets::prelude::*;
///
/// #[model]
/// struct Todo {
///     id: i64,        // primary key, generated by the database
///     title: String,
///     done: bool,
/// }
/// ```
///
/// It adds `#[derive(Clone, Debug, Serialize, Deserialize, Model)]` (the derives
/// you already wrote are kept), points the generated code to the crates re-exported
/// by `paquets` (no other dependency needed), and lets clients omit the generated
/// primary key in JSON bodies.
///
/// The table is named after the struct in `snake_case` (`Todo` → `todo`); choose
/// another name with `#[model(table = "todos")]`. Every Memoire attribute still works
/// on fields: `#[memoire(unique)]`, `#[memoire(index)]`, `#[memoire(primary_key)]`…
#[proc_macro_attribute]
pub fn model(args: TokenStream, item: TokenStream) -> TokenStream {
    let item = parse_macro_input!(item as ItemStruct);
    expand(args.into(), item, true)
        .unwrap_or_else(syn::Error::into_compile_error)
        .into()
}

/// Plain data that travels as JSON: forms, API payloads, configuration.
///
/// ```ignore
/// use paquets::prelude::*;
///
/// #[data]
/// struct Login {
///     email: String,
///     password: String,
/// }
/// ```
///
/// It adds `#[derive(Clone, Debug, Serialize, Deserialize)]` (the derives you already
/// wrote are kept), with the `serde` crate re-exported by `paquets`.
#[proc_macro_attribute]
pub fn data(args: TokenStream, item: TokenStream) -> TokenStream {
    let item = parse_macro_input!(item as ItemStruct);
    expand(args.into(), item, false)
        .unwrap_or_else(syn::Error::into_compile_error)
        .into()
}

fn expand(args: TokenStream2, mut item: ItemStruct, model: bool) -> syn::Result<TokenStream2> {
    let mut table: Option<LitStr> = None;
    if !args.is_empty() {
        let parser = syn::meta::parser(|meta| {
            if model && meta.path.is_ident("table") {
                let lit: LitStr = meta.value()?.parse()?;
                if lit.value().is_empty() {
                    return Err(meta.error("the table name cannot be empty"));
                }
                table = Some(lit);
                Ok(())
            } else if model {
                Err(meta.error("expected `table = \"...\"`"))
            } else {
                Err(meta.error("#[data] takes no arguments"))
            }
        });
        syn::parse::Parser::parse2(parser, args)?;
    }
    if !matches!(item.fields, Fields::Named(_)) {
        return Err(syn::Error::new_spanned(
            &item.ident,
            "paquets: only structs with named fields are supported",
        ));
    }

    let present = derived(&item.attrs)?;
    let mut derives = Vec::new();
    if !present.contains("Clone") {
        derives.push(quote!(::core::clone::Clone));
    }
    if !present.contains("Debug") {
        derives.push(quote!(::core::fmt::Debug));
    }
    if !present.contains("Serialize") {
        derives.push(quote!(::paquets::serde::Serialize));
    }
    if !present.contains("Deserialize") {
        derives.push(quote!(::paquets::serde::Deserialize));
    }
    if model && !present.contains("Model") {
        derives.push(quote!(::paquets::orm::Model));
    }

    let mut added = quote!(#[derive(#(#derives),*)]);
    if !mentions(&item.attrs, "serde", "crate") {
        added.extend(quote!(#[serde(crate = "::paquets::serde")]));
    }
    if model {
        if !mentions(&item.attrs, "memoire", "crate") {
            added.extend(quote!(#[memoire(crate = "::paquets::orm")]));
        }
        if let Some(table) = &table {
            added.extend(quote!(#[memoire(table = #table)]));
        }
        mark_generated_key(&mut item);
    }

    // The derives first: their helper attributes (`serde`, `memoire`) may only follow them.
    let mut attrs = Attribute::parse_outer.parse2(added)?;
    attrs.append(&mut item.attrs);
    item.attrs = attrs;
    Ok(quote!(#item))
}

/// The names (last path segment) of every derive already on the struct.
fn derived(attrs: &[Attribute]) -> syn::Result<HashSet<String>> {
    let mut names = HashSet::new();
    for attr in attrs.iter().filter(|a| a.path().is_ident("derive")) {
        let paths = attr.parse_args_with(Punctuated::<Path, Token![,]>::parse_terminated)?;
        for path in paths {
            if let Some(segment) = path.segments.last() {
                names.insert(segment.ident.to_string());
            }
        }
    }
    Ok(names)
}

/// Whether an attribute `#[name(...)]` contains the word `word`.
fn mentions(attrs: &[Attribute], name: &str, word: &str) -> bool {
    attrs
        .iter()
        .filter(|a| a.path().is_ident(name))
        .any(|a| match &a.meta {
            syn::Meta::List(list) => list
                .tokens
                .clone()
                .into_iter()
                .any(|t| t.to_string() == word),
            _ => false,
        })
}

/// An integer primary key is generated by the database: JSON bodies may omit it
/// (`#[serde(default)]`), as when a client creates a row.
fn mark_generated_key(item: &mut ItemStruct) {
    let Fields::Named(fields) = &mut item.fields else {
        return;
    };
    let explicit = fields.named.iter().position(|f| {
        mentions(&f.attrs, "memoire", "primary_key") || mentions(&f.attrs, "memoire", "id")
    });
    let key = explicit.or_else(|| {
        fields
            .named
            .iter()
            .position(|f| f.ident.as_ref().is_some_and(|i| i == "id"))
    });
    let Some(field) = key.map(|i| &mut fields.named[i]) else {
        return;
    };
    if is_integer(&field.ty) && !mentions(&field.attrs, "serde", "default") {
        field.attrs.push(syn::parse_quote!(#[serde(default)]));
    }
}

fn is_integer(ty: &Type) -> bool {
    match ty {
        Type::Path(p) if p.qself.is_none() => p.path.segments.last().is_some_and(|s| {
            s.arguments.is_empty() && matches!(s.ident.to_string().as_str(), "i16" | "i32" | "i64")
        }),
        _ => false,
    }
}
